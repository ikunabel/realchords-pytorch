#!/usr/bin/env python3
"""Generate the GAPT (RL) configs for the leave-one-out grid.

The MLE grid trained 2026-10-05 supplies the two inputs each RL run needs: the decoder
it initialises from and the encoder-decoder it is KL-regularised towards. Both are
picked here by minimum **aggregate** val/loss over that run's own training corpora --
the same rule as scripts/data/select_loo_checkpoints.py, and for the same reason: in a
leave-one-out run the held-out corpus has no validation loss, so a per-corpus rule is
undefined and would also let the held-out corpus influence model selection.

Reward models are the 7-set ensemble for every variant, not per-variant ones. The
transfer probe (journal/DATASET_MIX_LOO.md) found they separate genuine from corrupted
accompaniment at 0.87-0.98 AUC on corpora they never saw, so per-variant reward models
buy nothing -- that is why the LOO grid dropped 72 of its 123 planned jobs.

Usage:
    python scripts/data/generate_gapt_loo_configs.py --dry_run
    python scripts/data/generate_gapt_loo_configs.py
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, "scripts/data")
from select_loo_checkpoints import read_val_history  # noqa: E402

RUNS = Path("/hpcwork/thes2192/realchords/logs/my_logs")
SEVEN = ["hooktheory", "pop909", "emopia_plus", "nottingham",
         "wikifonia", "chord_melody_dataset", "jazzmus"]
VARIANTS = ["7sets", "hooktheory_only"] + [f"7sets_no_{d}" for d in SEVEN]
SEEDS = [42, 43, 44]
TEMPLATE = Path("configs/rl/gapt_7sets.alpha=0.5.seed=42.yml")


def best_ckpt(family: str, prefix: str, variant: str, seed: int) -> Path | None:
    """Lowest aggregate val/loss checkpoint for one cell, or None."""
    stems = [f"{prefix}{variant}.seed={seed}.alpha=0.5"]
    if variant == "hooktheory_only":
        stems.append(f"{prefix}{variant}.seed={seed}")      # older naming, no alpha
    dirs = []
    for stem in stems:
        dirs += [d for d in (RUNS / family).glob(stem + "*")
                 if d.is_dir() and list(d.glob("step=*.ckpt"))]
    if not dirs:
        return None
    run = max(dirs, key=lambda d: d.stat().st_mtime)
    ckpts = {int(c.stem.split("=")[1]): c for c in run.glob("step=*.ckpt")}
    usable = {s: v for s, v in read_val_history(run).items() if s in ckpts}
    return ckpts[min(usable, key=usable.get)] if usable else ckpts[max(ckpts)]


def decoder_include(variant: str, seed: int) -> str:
    stem = f"configs/decoder_only/decoder.chord.{variant}.seed={seed}.alpha=0.5.yml"
    if not Path(stem).exists() and variant == "hooktheory_only":
        stem = f"configs/decoder_only/decoder.chord.{variant}.seed={seed}.yml"
    return stem


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--dry_run", action="store_true")
    args = ap.parse_args()

    body = TEMPLATE.read_text(encoding="utf-8")
    made, missing = [], []
    print(f"{'cell':<42}{'decoder init':>16}{'enc-dec anchor':>18}")
    for variant in VARIANTS:
        for seed in SEEDS:
            dec = best_ckpt("decoder_only", "decoder.chord.", variant, seed)
            enc = best_ckpt("enc_dec", "enc_dec.chord.", variant, seed)
            inc = decoder_include(variant, seed)
            if dec is None or enc is None or not Path(inc).exists():
                missing.append((variant, seed,
                                "decoder" if dec is None else
                                "enc-dec" if enc is None else "include"))
                continue
            text = body
            text = text.replace(
                "configs/decoder_only/decoder.chord.7sets.seed=42.alpha=0.5.yml", inc)
            for key, path in (("pretrain_model_path", dec), ("anchor_model_path", enc)):
                old = [l for l in text.splitlines() if l.startswith(f"{key}:")][0]
                text = text.replace(old, f'{key}: "{path}"')
            header = (f"# GAPT on the {variant} mixture, seed {seed}, alpha 0.5.\n"
                      f"# Generated by scripts/data/generate_gapt_loo_configs.py.\n"
                      f"# Init and anchor are that variant's own MLE models, each the\n"
                      f"# lowest-aggregate-val/loss checkpoint of its run. Reward models are the\n"
                      f"# 7-set ensemble for every variant -- they were shown to transfer.\n")
            # "gapt_loo_" prefix, NOT "gapt_<variant>": the alpha sweep already owns
            # configs/rl/gapt_7sets.alpha=0.5.seed=*.yml, which document completed runs
            # initialised from different checkpoints, and its run dirs would collide.
            out = Path(f"configs/rl/gapt_loo_{variant}.alpha=0.5.seed={seed}.yml")
            if not args.dry_run:
                out.write_text(header + text, encoding="utf-8")
            made.append(out)
            print(f"{variant + ' s' + str(seed):<42}"
                  f"{dec.stem.split('=')[1]:>16}{enc.stem.split('=')[1]:>18}")
    if missing:
        print(f"\nMISSING ({len(missing)}):")
        for v, s, what in missing:
            print(f"  {v} seed={s}: no {what}")
    print(f"\n{'would write' if args.dry_run else 'wrote'} {len(made)} configs")


if __name__ == "__main__":
    main()
