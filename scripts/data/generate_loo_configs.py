"""Generate the reward and enc-dec configs for every dataset-mixture variant of the LOO grid.

The decoder configs already exist for all nine variants at seeds 42/43/44. Missing are the reward
models (4 kinds x 2 seeds) and the offline enc-dec anchor (3 seeds), which so far exist only for the
full 7-set mixture. Each is produced from its 7sets template by rewriting `datasets:`, `seed:` and
the checkpoint retention, leaving every other hyperparameter untouched so the variants stay
comparable with the existing 7sets runs.

Retention: the templates carry `checkpoint_top_k: -1` (keep every checkpoint), which costs 27 GB per
enc-dec run and ~10 GB per contrastive reward run -- 1.19 TB across this grid, against 276 GB of
headroom on /hpcwork/thes2192. Generated configs therefore set `checkpoint_top_k` (default 3), which
still leaves a choice of step when wiring the RL configs. See journal/DATASET_MIX_LOO.md.

Usage:
    python scripts/data/generate_loo_configs.py --dry_run
    python scripts/data/generate_loo_configs.py --top_k 3
"""

from __future__ import annotations

import argparse
import re
from pathlib import Path

SEVEN = ["hooktheory", "pop909", "nottingham", "wikifonia", "chord_melody_dataset", "jazzmus",
         "emopia_plus"]
# variant name -> datasets. "7sets" is the full mixture, "hooktheory_only" the single-corpus control.
VARIANTS = {"7sets": SEVEN, "hooktheory_only": ["hooktheory"]}
VARIANTS.update({f"7sets_no_{held}": [d for d in SEVEN if d != held] for held in SEVEN})

# reward templates: (directory, template stem, name of the generated stem) per seed slot
REWARD_TEMPLATES = [
    ("contrastive_reward", "contrastive_reward_7sets", "contrastive_reward_{v}"),
    ("contrastive_reward", "contrastive_reward_2_7sets", "contrastive_reward_2_{v}"),
    ("discriminative_reward", "discriminative_reward_128_bs_7sets", "discriminative_reward_128_bs_{v}"),
    ("discriminative_reward", "discriminative_reward_128_bs_2_7sets", "discriminative_reward_128_bs_2_{v}"),
    ("contrastive_reward", "contrastive_reward_no_augmentation_rhythm_7sets",
     "contrastive_reward_no_augmentation_rhythm_{v}"),
    ("contrastive_reward", "contrastive_reward_no_augmentation_rhythm_2_7sets",
     "contrastive_reward_no_augmentation_rhythm_2_{v}"),
    ("discriminative_reward", "discriminative_reward_no_augmentation_rhythm_7sets",
     "discriminative_reward_no_augmentation_rhythm_{v}"),
    ("discriminative_reward", "discriminative_reward_no_augmentation_rhythm_2_7sets",
     "discriminative_reward_no_augmentation_rhythm_2_{v}"),
]
ENC_DEC_TEMPLATE = ("enc_dec", "enc_dec.chord.7sets.seed=1.alpha=0.5")
ENC_DEC_SEEDS = [42, 43, 44]


def set_scalar(text: str, key: str, value: str) -> str:
    """Replace a top-level `key: ...` line, preserving nothing of the old value or its comment."""
    pattern = re.compile(rf"^{re.escape(key)}:.*$", re.MULTILINE)
    if not pattern.search(text):
        raise KeyError(f"no top-level '{key}:' to replace")
    return pattern.sub(f"{key}: {value}", text, count=1)


def header(variant: str, datasets: list, source: Path) -> str:
    return (f"# Auto-generated by scripts/data/generate_loo_configs.py for the dataset-mixture\n"
            f"# ablation (journal/DATASET_MIX_LOO.md). Variant: {variant}\n"
            f"# ({len(datasets)} dataset(s): {', '.join(datasets)}).\n"
            f"# Template: configs/{source}.yml -- every other hyperparameter is unchanged so this\n"
            f"# variant stays comparable with the 7sets runs.\n")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--configs", default="configs")
    ap.add_argument("--top_k", type=int, default=3,
                    help="checkpoint_top_k for generated configs (templates use -1 = keep all)")
    ap.add_argument("--dry_run", action="store_true")
    args = ap.parse_args()

    root = Path(args.configs)
    written = 0
    skipped: list = []
    for variant, datasets in VARIANTS.items():
        yaml_list = "[" + ", ".join(f'"{d}"' for d in datasets) + "]"
        for folder, template, out_stem in REWARD_TEMPLATES:
            src = root / folder / f"{template}.yml"
            text = src.read_text(encoding="utf-8")
            text = set_scalar(text, "datasets", yaml_list)
            text = set_scalar(text, "checkpoint_top_k",
                              f"{args.top_k} # {args.top_k} best by val/loss (template kept all)")
            out = root / folder / f"{out_stem.format(v=variant)}.yml"
            if out.resolve() == src.resolve():
                # the 7sets variant's own configs ARE the templates; leave them as the record of the
                # runs already trained against them and re-run them unmodified instead
                skipped.append(out)
                continue
            payload = header(variant, datasets, Path(folder) / template) + _strip_leading_comments(text)
            if not args.dry_run:
                out.write_text(payload, encoding="utf-8")
            written += 1
            print(f"  {'(dry) ' if args.dry_run else ''}{out}")
        folder, template = ENC_DEC_TEMPLATE
        src = root / folder / f"{template}.yml"
        base = src.read_text(encoding="utf-8")
        for seed in ENC_DEC_SEEDS:
            text = set_scalar(base, "datasets", yaml_list)
            text = set_scalar(text, "seed", str(seed))
            text = set_scalar(text, "checkpoint_top_k",
                              f"{args.top_k} # {args.top_k} best by val/loss (template kept all)")
            out = root / folder / f"enc_dec.chord.{variant}.seed={seed}.alpha=0.5.yml"
            payload = header(variant, datasets, Path(folder) / template) + _strip_leading_comments(text)
            if not args.dry_run:
                out.write_text(payload, encoding="utf-8")
            written += 1
            print(f"  {'(dry) ' if args.dry_run else ''}{out}")
    print(f"\n{written} config(s) {'would be ' if args.dry_run else ''}written")
    if skipped:
        print(f"{len(skipped)} left untouched because they are the templates themselves "
              f"(the 7sets variant reuses them, with checkpoint_top_k still -1):")
        for out in skipped:
            print(f"  = {out}")


def _strip_leading_comments(text: str) -> str:
    """Drop the template's own leading comment block, which describes the 7sets mixture."""
    lines = text.splitlines(keepends=True)
    i = 0
    while i < len(lines) and lines[i].lstrip().startswith("#"):
        i += 1
    return "".join(lines[i:])


if __name__ == "__main__":
    main()
